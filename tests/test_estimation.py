import numpy as np
import pandas as pd
import pytest

from mergersim.estimation import estimate_logit, estimate_nested_logit, two_sls


def simulated_logit_market_data(n_markets=300, n_products=6, alpha=-2.0, seed=0):
    """Logit data where firms price on unobserved quality xi, so price is endogenous.

    Each product has a fixed effect; a cost shifter w moves price but not utility (a valid instrument).
    """
    rng = np.random.default_rng(seed)
    rows = []
    fe = rng.normal(0, 0.5, n_products)
    for t in range(n_markets):
        w = rng.normal(0, 1, n_products)
        xi = rng.normal(0, 0.5, n_products)
        prices = 2 + 0.5 * w + 0.8 * xi + 0.1 * rng.normal(size=n_products)
        delta = fe + alpha * prices + xi
        shares = np.exp(delta) / (1 + np.exp(delta).sum())
        for j in range(n_products):
            rows.append({"market_ids": t, "product_ids": j, "firm_ids": j, "prices": prices[j],
                         "shares": shares[j], "cost_shifter": w[j], "nest": j % 2})
    df = pd.DataFrame(rows)
    df["outside_share"] = 1 - df.groupby("market_ids")["shares"].transform("sum")
    return df


def test_ols_is_biased_towards_zero_and_iv_corrects_it():
    df = simulated_logit_market_data()
    ols = estimate_logit(df)
    iv = estimate_logit(df, instruments=["cost_shifter"])
    assert ols.alpha > -1.9           # attenuated: demand looks less elastic
    assert iv.alpha == pytest.approx(-2.0, abs=0.1)
    assert iv.result.first_stage_f["prices"] > 100


def test_two_sls_exactly_identified_matches_ratio_formula():
    rng = np.random.default_rng(3)
    n = 500
    z = rng.normal(size=n)
    u = rng.normal(size=n)
    x = z + 0.5 * u + rng.normal(size=n)
    y = 1 + 2 * x + u
    exog = pd.DataFrame({"const": np.ones(n)})
    res = two_sls(pd.Series(y), exog, pd.DataFrame({"x": x}), pd.DataFrame({"z": z}))
    zc, xc, yc = z - z.mean(), x - x.mean(), y - y.mean()
    assert res.coef["x"] == pytest.approx((zc @ yc) / (zc @ xc))


def test_nested_logit_with_fixed_rho_recovers_alpha():
    """Data generated by plain logit are nested logit with rho = 0; fixing rho = 0 must give logit's alpha."""
    df = simulated_logit_market_data()
    fit = estimate_nested_logit(df, "nest", ["cost_shifter"], rho=0.0)
    logit = estimate_logit(df, instruments=["cost_shifter"])
    assert fit.alpha == pytest.approx(logit.alpha)


def test_fitted_logit_builds_market_models():
    df = simulated_logit_market_data(n_markets=50)
    fit = estimate_logit(df, instruments=["cost_shifter"])
    demand = fit.market(7)
    rows = fit.rows(7)
    # at observed prices the model reproduces observed shares exactly (delta includes xi)
    assert np.allclose(demand.shares(demand.prices0), df["shares"].to_numpy()[rows])
    assert demand.alpha == fit.alpha
